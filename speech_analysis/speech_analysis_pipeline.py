def transcribe_audio(audio_path):
    """
    음성 파일 경로를 받아 STT 텍스트를 반환한다.
    """

    audio_array, sampling_rate = librosa.load(
        str(audio_path),
        sr=16000,
        mono=True
    )

    result = asr(
        {
            "array": audio_array,
            "sampling_rate": sampling_rate
        },
        generate_kwargs={
            "language": "ko",
            "task": "transcribe"
        }
    )

    return result["text"].strip()

# STT 텍스트 전처리

def preprocess_stt_text(text):
    """
    STT 결과를 분석용으로 최소 전처리한다.
    의미를 바꾸는 수정은 하지 않는다.
    """

    if text is None:
        return ""

    text = str(text).strip()

    # 라벨/비언어 표기 제거
    text = re.sub(r"\((NO:|웃음|기침|잡음|소음|침묵|무음|음악)\)", " ", text)
    text = re.sub(r"\[(NO:|웃음|기침|잡음|소음|침묵|무음|음악)\]", " ", text)
    text = re.sub(r"<(NO:|웃음|기침|잡음|소음|침묵|무음|음악)>", " ", text)

    # 괄호 없이 NO:가 들어오는 경우
    text = re.sub(r"\bNO:\s*", " ", text)

    # 줄바꿈, 탭, 여러 공백 정리
    text = re.sub(r"\s+", " ", text)

    # 양끝 따옴표 제거
    text = text.strip(" \"'“”‘’")

    return text.strip()

# 반응 시간 측정 - 첫 소리 감지

def detect_first_sound_time(
    audio_path,
    sample_rate=16000,
    frame_duration=0.05,
    threshold_ratio=0.10,
    min_sound_duration=0.15
):
    """
    wav 파일 앞부분에서 처음 소리가 감지되는 시점을 초 단위로 반환한다.

    audio_path: 음성 파일 경로
    sample_rate: 음성 샘플레이트
    frame_duration: 소리 크기를 확인할 구간 길이(초)
    threshold_ratio: 전체 최대 소리 크기 대비 기준 비율
    min_sound_duration: 소리가 이 시간 이상 이어져야 실제 소리로 인정
    """

    y, sr = librosa.load(audio_path, sr=sample_rate, mono=True)

    if len(y) == 0:
        return None

    frame_length = int(sr * frame_duration)
    min_sound_frames = max(1, int(min_sound_duration / frame_duration))

    max_amplitude = np.max(np.abs(y))

    if max_amplitude == 0:
        return None

    threshold = max_amplitude * threshold_ratio

    sound_flags = []

    for start in range(0, len(y), frame_length):
        frame = y[start:start + frame_length]

        if len(frame) == 0:
            continue

        frame_amplitude = np.mean(np.abs(frame))
        is_sound = frame_amplitude >= threshold
        sound_flags.append(is_sound)

    consecutive = 0

    for i, is_sound in enumerate(sound_flags):
        if is_sound:
            consecutive += 1

            if consecutive >= min_sound_frames:
                first_frame_index = i - min_sound_frames + 1
                first_sound_time = first_frame_index * frame_duration
                return round(first_sound_time, 2)
        else:
            consecutive = 0

    return None

def calculate_response_time_from_audio(audio_path):
    """
    음성 파일에서 첫 소리 감지 시점을 반응 시간으로 사용한다.
    """

    return detect_first_sound_time(audio_path)

# 반복어 비율 계산

def tokenize_text(text):
    """
    STT 텍스트를 공백 기준 어절로 분리한다.
    문장부호는 반복어 계산에 방해되므로 제거한다.
    """

    if text is None:
        return []

    text = str(text).strip()

    if text == "":
        return []

    # 문장부호 제거
    text = re.sub(r"[.,!?。！？…~]+", " ", text)

    # 괄호, 따옴표 등 제거
    text = re.sub(r"[\"'“”‘’()\[\]{}<>]", " ", text)

    # 여러 공백 정리
    text = re.sub(r"\s+", " ", text).strip()

    if text == "":
        return []

    return text.split(" ")


def calculate_repetition_ratio(text):
    """
    연속 반복 어절 비율을 계산한다.
    반환값은 퍼센트(%) 단위 float.
    """

    tokens = tokenize_text(text)

    if len(tokens) == 0:
        return 0.0

    repeated_count = 0

    for i in range(1, len(tokens)):
        if tokens[i] == tokens[i - 1]:
            repeated_count += 1

    ratio = repeated_count / len(tokens) * 100

    return round(ratio, 2)


def score_repetition_ratio(repetition_ratio):
    """
    반복어 비율을 0~100점으로 변환한다.
    낮을수록 좋은 점수다.
    """

    if repetition_ratio is None:
        return 0

    if repetition_ratio <= 5:
        return 100
    elif repetition_ratio <= 15:
        return 80
    elif repetition_ratio <= 30:
        return 60
    elif repetition_ratio <= 50:
        return 40
    else:
        return 0


def analyze_repetition(text):
    """
    STT 텍스트에서 반복어 비율과 반복어 점수를 함께 계산한다.
    """

    repetition_ratio = calculate_repetition_ratio(text)
    repetition_score = score_repetition_ratio(repetition_ratio)

    return {
        "repetition_ratio": repetition_ratio,
        "repetition_score": repetition_score
    }

