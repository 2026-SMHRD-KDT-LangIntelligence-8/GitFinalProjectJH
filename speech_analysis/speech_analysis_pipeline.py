# 공통 프롬프트 조립 함수

def build_appropriateness_prompt(
    question_type_name,
    question_text,
    stt_text,
    image_description=None
):
    if question_type_name not in APPROPRIATENESS_PROMPTS:
        raise ValueError(f"알 수 없는 문항 유형입니다: {question_type_name}")

    if image_description is None:
        image_description = ""

    prompt = APPROPRIATENESS_PROMPTS[question_type_name]

    prompt = (
        prompt
        .replace("{question_text}", question_text)
        .replace("{stt_text}", stt_text)
        .replace("{image_description}", image_description)
    )

    return prompt

# 점수 파싱 함수

def parse_score(raw_output):
    """
    LLM 출력에서 0, 40, 60, 80, 100 중 하나만 추출한다.
    """

    text = str(raw_output).strip()

    if text.isdigit():
        score = int(text)
        if score in VALID_SCORES:
            return score

    numbers = re.findall(r"\b(?:0|40|60|80|100)\b", text)

    if len(numbers) == 1:
        score = int(numbers[0])
        if score in VALID_SCORES:
            return score

    raise ValueError(f"점수 형식이 올바르지 않습니다. LLM 출력: {raw_output}")

# 화행 적절성 채점 함수

def score_appropriateness_with_llm(
    question_type_name,
    question_text,
    stt_text,
    image_description=None
):
    """
    문항 유형, 문항, STT 답변을 바탕으로 화행 적절성 점수를 계산한다.
    반환값: 0, 40, 60, 80, 100 중 하나
    """

    if client is None:
        raise ValueError("OPENAI_API_KEY 환경변수가 설정되어 있지 않아 LLM 채점을 실행할 수 없습니다.")

    prompt = build_appropriateness_prompt(
        question_type_name=question_type_name,
        question_text=question_text,
        stt_text=stt_text,
        image_description=image_description
    )

    response = client.responses.create(
        model=LLM_MODEL_NAME,
        input=prompt,
        temperature=0,
        max_output_tokens=32,
    )

    raw_output = response.output_text.strip()
    score = parse_score(raw_output)

    return score

# 통합 채점 함수

def analyze_question_answer(
    audio_path,
    question_type_name,
    question_text,
    image_description=None,
    use_llm_scoring=True
):
    """
    음성 답변 파일 하나를 분석하여 DB 저장 및 리포트 생성에 필요한 값을 반환한다.

    audio_path: 녹음된 음성 파일 경로
    question_type_name: 문항 유형명
    question_text: 사용자에게 제시된 문항 텍스트
    image_description: 그림 설명하기 문항의 이미지 설명 기준. 다른 유형은 None.
    use_llm_scoring: 화행 적절성 LLM 채점을 실행할지 여부
    """

    # 1. 음성 파일 → STT 텍스트
    stt_text = transcribe_audio(audio_path)

    # 2. STT 텍스트 최소 전처리
    preprocessed_text = preprocess_stt_text(stt_text)

    # 3. 음성 파일 기반 반응 시간 계산
    response_time = calculate_response_time_from_audio(audio_path)

    # 4. 반복어 비율 계산
    repetition_result = analyze_repetition(preprocessed_text)

    # 5. 답변 전체 의미 글자 수 계산
    length_result = analyze_answer_length(
        preprocessed_text,
        question_type_name
    )

    # 6. 화행 적절성 LLM 채점
    if use_llm_scoring:
        appropriateness_score = score_appropriateness_with_llm(
            question_type_name=question_type_name,
            question_text=question_text,
            stt_text=preprocessed_text,
            image_description=image_description
        )
    else:
        appropriateness_score = None

    # 7. 최종 분석 결과 반환
    return {
        # QUESTION_RESULTS에 저장할 값
        "audio_file_path": str(audio_path),
        "stt_text": stt_text,
        "preprocessed_text": preprocessed_text,

        # ANALYSIS_RESULTS에 저장할 값
        "response_time": response_time,
        "repetition_ratio": repetition_result["repetition_ratio"],
        "avg_sentence_length": length_result["avg_sentence_length"],
        "appropriateness_score": appropriateness_score,

        # 리포트 계산용 보조 점수
        "repetition_score": repetition_result["repetition_score"],
        "sentence_length_score": length_result["sentence_length_score"],
    }

# 리포트 요약 함수

def calculate_average(values):
    """
    None을 제외하고 평균을 계산한다.
    값이 없으면 None을 반환한다.
    """

    valid_values = [
        value for value in values
        if value is not None
    ]

    if len(valid_values) == 0:
        return None

    return round(sum(valid_values) / len(valid_values), 2)


def score_response_time(response_time):
    """
    반응 시간을 0~100점으로 변환한다.
    단위: 초
    """

    if response_time is None:
        return 0

    if response_time <= 3:
        return 100
    elif response_time <= 5:
        return 80
    elif response_time <= 8:
        return 60
    elif response_time <= 12:
        return 40
    else:
        return 0
    
